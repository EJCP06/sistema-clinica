const express = require('express');
const cors = require('cors');
const helmet = require('helmet');
const http = require('http');
const { Server } = require('socket.io');
const dotenv = require('dotenv');
const pool = require('./src/config/db');

// Configuración de variables de entorno
const path = require('path');
dotenv.config({ path: path.join(__dirname, '.env') });

// Inicialización de la aplicación
const app = express();
const server = http.createServer(app);

// Seguridad HTTP headers
app.use(helmet());

// Configuración de Socket.io
const io = new Server(server, {
  cors: {
    origin: ['http://localhost:4200', 'http://localhost:4201', 'http://localhost'], // Restringir a dominios específicos
    methods: ['GET', 'POST', 'PUT', 'DELETE'],
  },
});

// Middlewares
app.use(cors({
  origin: ['http://localhost:4200', 'http://localhost:4201', 'http://localhost'],
  methods: ['GET', 'POST', 'PUT', 'DELETE', 'OPTIONS'],
  allowedHeaders: ['Content-Type', 'Authorization'],
  credentials: true
}));
app.use(express.json());

// Hacer io accesible desde los controladores u otras rutas si es necesario
app.use((req, res, next) => {
  req.io = io;
  next();
});

// Prueba de conexión a la Base de Datos
pool.query('SELECT NOW()', async (err, res) => {
  if (err) {
    console.error('❌ Error al conectar con la base de datos:', err);
  } else {
    console.log('✅ Conexión a PostgreSQL exitosa, hora del servidor:', res.rows[0].now);

    try {
      await pool.query(
        'ALTER TABLE "Atencion" ADD COLUMN IF NOT EXISTS id_consultorio INTEGER REFERENCES "Consultorios"("id_consultorio")'
      );
      console.log('✅ Columna id_consultorio asegurada en tabla Atencion');

      await pool.query(
        'ALTER TABLE "Atencion" ADD COLUMN IF NOT EXISTS id_cliente INTEGER REFERENCES "cliente"("id_cliente")'
      );
      console.log('✅ Columna id_cliente asegurada en tabla Atencion');

      await pool.query('DROP TABLE IF EXISTS "turnos" CASCADE');
      console.log('✅ Tabla legacy turnos eliminada de la base de datos actual si existía');

      await pool.query(`
        CREATE TABLE IF NOT EXISTS "tipo_cliente" (
          "id_tipo_cliente" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          "nombre" varchar NOT NULL
        );

        CREATE TABLE IF NOT EXISTS "cliente" (
          "id_cliente" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          "id_tipo_cliente" integer NOT NULL REFERENCES "tipo_cliente"("id_tipo_cliente"),
          "nombre" varchar NOT NULL,
          "id_sede" integer REFERENCES "Sedes"("id_sede")
        );

        INSERT INTO "tipo_cliente" ("id_tipo_cliente", "nombre") VALUES
          (1, 'Particular'),
          (2, 'Aseguradora')
        ON CONFLICT ("id_tipo_cliente") DO UPDATE SET
          "nombre" = EXCLUDED."nombre";
      `);
      console.log('✅ Tablas tipo_cliente y cliente aseguradas en la base de datos');
    } catch (alterError) {
      console.error('❌ Error al asegurar las tablas nuevas en la base de datos:', alterError);
    }
  }
});

// Rutas base
app.get('/api/health', (req, res) => {
  res.status(200).json({ status: 'ok', message: 'API funcionando correctamente' });
});

